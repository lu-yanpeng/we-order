-- 周期兜底扫描：定时任务声明（Story 4.2；FR-P2-11；AR-6、AR-13、AR-19）
--
-- 机制与触发分离（AD-6）：本迁移只注册「什么时候调用」，推进实现一份不动。
--   * 任务调用 public.advance_due_orders()（不传用户 = 全部到点订单），与读时推进
--     （Story 5.1，传调用者用户）是同一个函数——兜底与读时不会各写一套后漂移；
--     函数不绑定归属，未来 Phase 4 换商家触发时机制不用重写。
--   * 函数体内的到点判定只看 ready_at（下单时按 stores.ready_delay_seconds 写入）；
--     扫描频率是「多久查一次」，不是业务参数，不参与「何时该推进」的判定。
--
-- 周期 15 秒是演示参数：无人读取时，订单最晚在「到点 + 一个扫描周期」内被推进
-- （默认推进时长 15 秒，故最坏约 30 秒）；有人读取时由读时推进即时生效，扫描只兜底。
-- 平台只支持周期任务、不支持「事件发生后延时 N 秒执行一次」（AR-19），本任务即周期兜底那一半。
--
-- 失败与重跑（NFR2）：一次执行是一个事务，任何一步失败整体回滚、不留中间态；下一个周期照常重试，
-- 重复执行不产生第二个取杯号、不跳状态（Story 4.1 的带状态谓词更新保证幂等）。
-- 运行历史在 cron.job_run_details（每次执行的时间、状态与错误信息）；历史清理按架构约定留待
-- 实例长期运行时再加。
--
-- 注意：migration squash 会丢弃 cron 任务，使用前须知会丢什么（AR-6）。

-- 本地栈需要显式安装（云端托管项目默认已启用，此时本句是空操作）。
create extension if not exists pg_cron with schema pg_catalog;

-- 命名任务：同名重复注册是「替换」而不是「新增」，迁移重放不会留下第二个任务。
select cron.schedule(
  'advance-due-orders',
  '15 seconds',
  'select public.advance_due_orders()'
);
